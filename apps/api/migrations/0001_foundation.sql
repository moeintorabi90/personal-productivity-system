-- Stage 1 foundation: owner account, devices, sessions, preferences, sync log.
-- Never edit this file after it has been applied anywhere; add a new numbered migration.

-- Exactly one owner per installation (D-005). The singleton row makes setup race-free.
CREATE TABLE app_user (
  id uuid PRIMARY KEY,
  email text NOT NULL,
  password_hash text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX app_user_email_key ON app_user (lower(email));

CREATE TABLE app_installation (
  singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
  owner_id uuid NOT NULL UNIQUE REFERENCES app_user (id) ON DELETE RESTRICT,
  completed_at timestamptz NOT NULL DEFAULT now()
);

-- Device IDs are generated by clients, so they are only unique per owner.
CREATE TABLE sync_device (
  user_id uuid NOT NULL REFERENCES app_user (id) ON DELETE RESTRICT,
  id uuid NOT NULL,
  name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 80),
  created_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz,
  revoked_at timestamptz,
  PRIMARY KEY (user_id, id)
);

-- Only a SHA-256 hash of the bearer token is stored.
CREATE TABLE auth_session (
  id uuid PRIMARY KEY,
  user_id uuid NOT NULL,
  device_id uuid NOT NULL,
  token_hash text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  FOREIGN KEY (user_id, device_id) REFERENCES sync_device (user_id, id) ON DELETE RESTRICT
);
CREATE INDEX auth_session_user_device_idx ON auth_session (user_id, device_id);

CREATE TABLE user_preference (
  user_id uuid PRIMARY KEY REFERENCES app_user (id) ON DELETE RESTRICT,
  language text NOT NULL CHECK (language IN ('en', 'fa')),
  theme text NOT NULL CHECK (theme IN ('system', 'light', 'dark')),
  calendar_display text NOT NULL CHECK (calendar_display IN ('gregorian', 'jalali', 'both')),
  week_start smallint NOT NULL CHECK (week_start BETWEEN 0 AND 6),
  time_zone text CHECK (time_zone IS NULL OR char_length(time_zone) BETWEEN 1 AND 64),
  revision integer NOT NULL CHECK (revision >= 1),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Diagnostic record proving create/update/delete sync before Stage 2 (DECISIONS T-011).
-- Deleted rows keep a tombstone (deleted_at) instead of being removed.
CREATE TABLE sync_probe (
  user_id uuid NOT NULL REFERENCES app_user (id) ON DELETE RESTRICT,
  id uuid NOT NULL,
  text text NOT NULL CHECK (char_length(text) BETWEEN 1 AND 500),
  revision integer NOT NULL CHECK (revision >= 1),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  PRIMARY KEY (user_id, id)
);

-- Results of applied push operations, so a retried operation returns the original result.
CREATE TABLE sync_operation (
  user_id uuid NOT NULL REFERENCES app_user (id) ON DELETE RESTRICT,
  op_id uuid NOT NULL,
  device_id uuid NOT NULL,
  request_hash text NOT NULL,
  result jsonb NOT NULL,
  applied_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, op_id)
);

-- Append-only change stream read by GET /v1/sync/pull. Deletions are rows with deleted = true.
CREATE TABLE change_log (
  seq bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES app_user (id) ON DELETE RESTRICT,
  record_type text NOT NULL CHECK (record_type IN ('preferences', 'sync_probe')),
  record_id uuid NOT NULL,
  revision integer NOT NULL CHECK (revision >= 1),
  deleted boolean NOT NULL DEFAULT false,
  data jsonb,
  device_id uuid,
  op_id uuid,
  changed_at timestamptz NOT NULL DEFAULT now(),
  CHECK (deleted OR data IS NOT NULL)
);
CREATE INDEX change_log_user_seq_idx ON change_log (user_id, seq);
